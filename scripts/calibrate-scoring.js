#!/usr/bin/env node
// Builds shared/score-calibration.js from the collected win-probability dataset.
//
// Each component (suspense, surprise, finish, twist, pacing) is reported on a
// 0-10 scale equal to its percentile among that sport's games, so a Suspense of
// 8.0 means "more suspenseful than 80% of NBA games". The composite is mapped
// onto the sport's established score distribution (quantile mapping), which
// keeps tier rates and thresholds stable while the ranking follows the model.
//
// Usage: node scripts/build-suspense-table.js && node scripts/calibrate-scoring.js
// The target distribution is the stored score (`ex`) of each game in the dataset.

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { gunzipSync } from 'zlib';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { computeBeliefMetrics } from '../shared/belief-metrics.js';
import { componentValues, compositeFromPercentiles, percentileOf as percentile, COMPONENT_KEYS } from '../shared/scoring-model.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATASET = join(ROOT, 'analysis', 'wp-dataset');
const OUT = join(ROOT, 'shared', 'score-calibration.js');
const KNOTS = 101;

function quantiles(values) {
  const sorted = [...values].sort((a, b) => a - b);
  return Array.from({ length: KNOTS }, (_, i) => {
    const pos = (i / (KNOTS - 1)) * (sorted.length - 1);
    const lo = Math.floor(pos);
    const hi = Math.min(sorted.length - 1, lo + 1);
    return Number((sorted[lo] + (sorted[hi] - sorted[lo]) * (pos - lo)).toPrecision(5));
  });
}

const calibration = { knots: KNOTS, sports: {} };
for (const sport of ['NFL', 'CFB', 'NBA', 'MLB']) {
  const file = join(DATASET, `${sport.toLowerCase()}.json.gz`);
  if (!existsSync(file)) continue;
  const { games } = JSON.parse(gunzipSync(readFileSync(file)));
  const reference = games.filter(g => g.file && typeof g.ex === 'number' && g.p.length >= 10);
  const comps = reference.map(g => componentValues(computeBeliefMetrics(g.p.map(v => v / 10000), sport)));
  const components = {};
  for (const key of COMPONENT_KEYS) components[key] = quantiles(comps.map(c => c[key]));
  const composites = comps.map(c => {
    const pct = {};
    for (const key of COMPONENT_KEYS) pct[key] = percentile(components[key], c[key]);
    return compositeFromPercentiles(pct);
  });
  calibration.sports[sport] = {
    games: reference.length,
    components,
    composite: quantiles(composites),
    score: quantiles(reference.map(g => g.ex))
  };
  console.log(`${sport}: calibrated on ${reference.length} games`);
}

const header = `// GENERATED by scripts/calibrate-scoring.js — do not edit by hand.
// Per-sport quantile knots (0th..100th percentile) for each scoring component,
// the composite, and the published score distribution it maps onto.
// Built ${new Date().toISOString().slice(0, 10)} from analysis/wp-dataset.
`;
writeFileSync(OUT, `${header}export const SCORE_CALIBRATION = ${JSON.stringify(calibration)};\n`);
console.log(`Wrote ${OUT}`);
